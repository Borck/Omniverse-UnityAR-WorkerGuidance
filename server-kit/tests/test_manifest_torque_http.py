"""The HTTP manifest must carry the authored stepType and targetTorqueNm.

These are the values the client needs to stop using its hardcoded 1 Nm fallback
and its "does the display name contain the word tighten" heuristic. They are
authored per step in assembly_definition.json and travel: export report ->
nucleus_job_service -> manifest.json -> this endpoint -> Unity.

Self-contained (own tmp manifests root, explicit AppConfig) so it does not
depend on a checked-in fixture or on the working directory.
"""
from pathlib import Path
import json
import sys

from fastapi.testclient import TestClient

sys.path.append(str(Path(__file__).resolve().parents[1] / "app"))

from config import AppConfig
from server_kit_main import create_app


def _client(tmp_path: Path, steps: list[dict]) -> TestClient:
    manifests_root = tmp_path / "manifests"
    manifests_root.mkdir(parents=True, exist_ok=True)
    (manifests_root / "job-torque-001.manifest.json").write_text(
        json.dumps({
            "jobId": "job-torque-001",
            "workflowVersion": "1.0.0",
            "steps": steps,
        }),
        encoding="utf-8",
    )
    return TestClient(create_app(AppConfig(
        manifests_root=manifests_root,
        session_store_file=tmp_path / "sessions.json",
    )))


def _step(**overrides) -> dict:
    step = {
        "stepId": "6.2",
        "partId": "screw_12",
        "assetVersion": "sha256_abc",
        "glbFile": "part_screw_12_abc.glb",
        "stepJsonFile": "6_2.json",
        "targetVersion": "Segment_Assembly",
        "targetFile": "Segment_Assembly_Fixture.dat",
        "compression": "NONE",
    }
    step.update(overrides)
    return step


def test_screwing_step_carries_its_authored_torque(tmp_path: Path) -> None:
    client = _client(tmp_path, [_step(stepType="screwing", targetTorqueNm=2.5)])

    body = client.get("/api/jobs/job-torque-001/manifest").json()

    step = body["steps"][0]
    assert step["stepType"] == "screwing"
    assert step["targetTorqueNm"] == 2.5


def test_step_without_torque_reports_zero_not_null(tmp_path: Path) -> None:
    """Unity parses this with JsonUtility, which cannot represent an absent
    float -- it would turn null into 0.0 anyway. So the endpoint says 0.0 and
    stepType is what tells the client whether a torque was expected."""
    client = _client(tmp_path, [_step(stepType="fitting", targetTorqueNm=None)])

    step = client.get("/api/jobs/job-torque-001/manifest").json()["steps"][0]

    assert step["stepType"] == "fitting"
    assert step["targetTorqueNm"] == 0.0


def test_manifest_written_before_these_fields_still_loads(tmp_path: Path) -> None:
    """Backward compatibility: the manifest and the server are regenerated by
    different things at different times, so an older manifest.json must not
    500 the endpoint."""
    client = _client(tmp_path, [_step()])          # no stepType, no targetTorqueNm

    response = client.get("/api/jobs/job-torque-001/manifest")

    assert response.status_code == 200
    step = response.json()["steps"][0]
    assert step["stepType"] == ""
    assert step["targetTorqueNm"] == 0.0
    # and the pre-existing fields are untouched
    assert step["stepId"] == "6.2"
    assert step["glbUrl"] == "/api/assets/sha256_abc/part_screw_12_abc.glb"
